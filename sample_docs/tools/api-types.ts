  Fourth = 4,
  /** Пятый уровень: Големная печь, 4 головы в неделю. */
  Fifth = 5,
  /** Шестой уровень: Гнездовой навес, 3 головы в неделю, «и ни одной больше». */
  Sixth = 6,
  /** Седьмой уровень: Горн зова, 1 голова в неделю плюс слиток. */
  Seventh = 7,
  /** Академия огня: вне пирамиды по настоянию ректора Флавии Двухфитильной. */
  Special = 'особое',
