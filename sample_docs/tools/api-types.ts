/** Коридор урона одной головы: числа и каноническое отображение через дефис. */
export interface DamageRange {
  /** Минимальный урон; у Лавового Дракона — 40, «дракон ударил как дракон». */
  damage_min: number;
  /** Максимальный урон; у Лавового Дракона — 63, «как дракон Кальдеры». */
  damage_max: number;
  /** Готовая строка отображения («40-63»); словесные формы запрещены поиском. */
  damage_display: string;
}

/**
 * Карточка существа пирамиды или Академии.
 *
 * Поля один в один повторяют выгрузку `data/creature-stats.json`, кроме
 * необязательных `legacy_name` и `naming_note`, которые хранят историю
 * переименования «Обсидианного» в «Обсидианового» голема (сборка 0.6.2).
 */
export interface Creature extends DamageRange {
  /** Латинский идентификатор; канонический ключ всех справочников. */
  id: CreatureId;
  /** Русское имя («Искровик», «Лавовый Дракон»). */
  name: string;
  /** Уровень пирамиды: 1-7 или «особое» для Академии огня. */
  tier: CreatureTier | number;
  /** Жилище города, дающее прирост. */
  dwelling: string;
  /** Базовая атака без героя и артефактов. */
  attack: number;
  /** Базовая защита без героя и артефактов. */
  defense: number;
  /** Здоровье одной головы. */
  health: number;
  /** Скорость в бою; гарпии — самые быстрые (11-12), големы — «медленно, но навсегда». */
  speed: number;
  /** Недельный прирост жилища; неизменен с Гарнизонного устава 908 года. */
  growth: number;
  /** Цена найма в золоте. */
  cost_gold: number;
  /** Цена найма в клейменых слитках; `null` для всех, кроме драконов. */
  cost_ingots: number | null;
  /** Эффективная цена в золоте по городскому курсу слитка (250). */
  effective_cost_gold: number;
  /** Внутренний вес отряда для боевого искателя ИИ. */
  ai_value: number;
  /** Идентификатор апгрейда, если он существует. */
  upgrades_to?: CreatureId;
  /** Идентификатор базового существа, если это апгрейд. */
  upgrade_of?: CreatureId;
  /** Старое написание имени; оставлено для поискового индекса базы. */
  legacy_name?: string;
  /** Примечание о переименовании (см. «Обсидианный» → «Обсидиановый»). */
  naming_note?: string;
  /** Короткая сводка ключевой особенности. */
  special: string;
  /** Подробности особенности; порядок строк повторяет выгрузку. */
  special_details: string[];
  /** Сводка лора; полная версия — в lore/creatures.md. */
  lore_summary: string;
  /** Комментарий балансовой группы: «почему числа именно такие». */
  balance_note: string;
}

/** Пара «база → апгрейд» с дельтами статов; правило — коридор 30-45%. */
export interface UpgradePair {
  /** Человекочитаемое имя пары («Молот → Чёрный молот»). */
  pair: string;
  /** Прибавка атаки. */
  attack: number;
  /** Прибавка защиты. */
  defense: number;
  /** Прибавка здоровья. */
  health: number;
  /** Прибавка урона. */
  damage: number;
  /** Прибавка скорости; 0 у големов — «медленно, но навсегда». */
  speed: number;
  /** Способность, которую приносит апгрейд. */
  new_ability: string;
  /** Исключение из коридора; задокументировано только у драконьей пары. */
  exception?: string;
}

/** Строка недельной экономики жилища: головы, золото и доля пирамиды. */
export interface WeeklyEconomyRow {
  /** Название жилища («Горн зова»). */
  dwelling: string;
  /** Голов в неделю при базовых постройках. */
  heads_per_week: number;
  /** Золото за неделю полной покупки. */
  gold_per_week: number;
  /** Дополнительный расход слитками («1 слиток» у Горна зова). */
  extra?: string;
  /** Доля пирамиды в процентах; итог — 100. */
  share_percent: number;
}

/** Итог недельной пирамиды: 46 голов, 7770 золота и 1 слиток. */
export interface WeeklyEconomyTotal extends WeeklyEconomyRow {
  /** Всегда 100: строка итога. */
  share_percent: 100;
}

/** Экономика клейменого слитка: третья валюта города. */
export interface ObsidianEconomy {
  /** Курс слитка в городе: 250 золотых. */
  ingot_city_rate_gold: number;
  /** Курс у эрафийских торговцев: 180; обратная продажа — с потерей трети. */
  ingot_erathian_traders_rate_gold: number;
  /** Правила обращения слитков текстом; источник — раздел «Методика». */
  rules: string[];
}

/** Тариф ремонта големов: 47 золота за ХП, не менялся с 0.7.3. */
export interface GolemRepairTariff {
  /** Базовая цена за единицу здоровья. */
  base_price_gold_per_hp: number;
  /** Сборка, в которой тариф закреплён. */
  unchanged_since_build: string;
  /** Полный ремонт Обсидианового голема (50 ХП): 2350 золота. */
  full_repair_obsidian_golem_gold: number;
  /** Половинный ремонт: 1175. */
  half_repair_obsidian_golem_gold: number;
  /** Скидка специализации Орна Тлеющего Круга: 0,2. */
  orn_discount: number;
  /** Тариф Орна с округлением вверх: 38 золота за ХП. */
  orn_price_gold_per_hp: number;
  /** Полный ремонт тарифом Орна: 1900. */
  orn_full_repair_gold: number;
  /** Правила ремонта текстом. */
  rules: string[];
}

/** Проверенная синергия пары отрядов («Голем и волк», «Гарпия и фитиль»). */
export interface SynergyPair {
  /** Имя пары в кавычках-«ёлочках». */
  name: string;
  /** Состав пары. */
  composition: string;
  /** Численный эффект (+18% к обмену и т.п.). */
  effect: string;
  /** Поговорка, закреплённая за парой. */
  proverb: string;
}

/** Влияние специализации героя на существ; сводка из раздела 11. */
export interface HeroEffectOnCreatures {
  /** Имя героя («Орн Тлеющий Круг»). */
  hero: string;
  /** Описание специализации словами. */
  specialization: string;
  /** Численное выражение («47 → 38 золота за ХП»). */
  numeric: string;
}

/** Эталон оригинальной игры, задающий коридор силы уровня. */
export interface EtalonEntry {
  /** Имя эталона («Мечник»). */
  name: string;
  /** Город оригинала («Замок»). */
  town: string;
  /** Уровни дополнения, для которых эталон работает. */
  used_for: Array<CreatureTier | number | 'особое'>;
  /** Статы эталона. */
  attack: number;
  defense: number;
  health: number;
  damage_min: number;
  damage_max: number;
  speed: number;
  /** Цена эталона; `null` для существ, которых не нанимают. */
  cost_gold: number | null;
  /** Что именно заимствовано у эталона. */
  borrowed: string;
}

/**
 * Полный документ выгрузки статов — контракт `GET /api/v1/creatures/stats`.
 *
 * Соответствует файлу `data/creature-stats.json` сборки 0.9.4.
 */
export interface CreatureStatsDocument {
  /** Версия выгрузки. */
  version: string;
  /** Дата генерации в формате ISO-кода «2026-09-14». */
  generated: string;
  /** Идентификатор генератора (tools/docgen.md). */
  generator: string;
  /** Источник истины: balance/creature-stats.md. */
  source_of_truth: string;
  /** Статус документа базы: автогенерация, вручную не редактировать. */
  status: string;
  /** Смежные документы для навигации по базе. */
  see_also: string[];
  /** Пирамида и Академия: шестнадцать существ. */
  creatures: Creature[];
  /** Дельты апгрейдов с правилом коридора. */
  upgrade_deltas: {
    /** Формулировка правила 30-45%. */
    rule: string;
    /** Восемь пар «база → апгрейд». */
    pairs: UpgradePair[];
  };
  /** Недельная экономика пирамиды. */
  weekly_economy: {
    /** Примечание об условиях подсчёта. */
    note: string;
    /** Строки жилищ; порядок повторяет раздел 2.3. */
    rows: WeeklyEconomyRow[];
    /** Итоговая строка. */
    total: WeeklyEconomyTotal;
  };
  /** Экономика клейменого слитка. */
  obsidian_economy: ObsidianEconomy;
  /** Тариф ремонта големов. */
  golem_repair: GolemRepairTariff;
  /** Проверенные синергии; по 200 боёв на пару, сборка 0.9.4. */
  synergies: {
    /** Метка сверки. */
    verified: string;
    /** Четыре канонические пары. */
    pairs: SynergyPair[];
  };
  /** Влияния специализаций героев на существ. */
  hero_effects_on_creatures: HeroEffectOnCreatures[];
  /** Библиотека эталонов оригинальной игры. */
  etalons: {
    /** Ссылка на инструмент сверки (tools/statdiff.md). */
    library: string;
    /** Правило доверия: верьте оригиналу, а библиотеку поправьте. */
    note: string;
    /** Эталонные существа оригинала. */
    list: EtalonEntry[];
  };
  /** Псевдонимы поискового индекса (легаси-имена). */
  search_index_aliases: Array<{
    /** Старая форма («Обсидианный голем»). */
    legacy: string;
    /** Каноническая форма. */
    canonical: string;
    /** Сборка, с которой действует канон. */
    since: string;
    /** Причина сохранения псевдонима. */
    reason: string;
  }>;
}

