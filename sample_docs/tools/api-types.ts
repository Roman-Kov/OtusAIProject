/**
 * api-types.ts — типы API тестового стенда дополнения «Трон Пепла».
 *
 * Файл описывает контракты тестового стенда команды: существо, герой,
 * артефакт, армия и результат боя. Поля типов согласованы с машинной
 * выгрузкой `sample_docs/data/creature-stats.json` (сборка 0.9.4) и с
 * лор-документами раздела `sample_docs/lore/`: переименование поля здесь
 * без синхронной правки выгрузки карается сверкой, ибо тестовый стенд
 * читает и то и другое, а город, который обманывает в счёте, обманывает и
 * в погоде. Это файл типов: исполняемого кода здесь нет и не будет.
 *
 * Соглашения кодирования, отражённые в типах:
 * - урон передаётся тройкой `damage_min` / `damage_max` /
 *   `damage_display`, где отображение всегда пишется через дефис («40-63»);
 * - цены со слитками передаются парой `cost_gold` / `cost_ingots` и
 *   готовой суммой `effective_cost_gold` по городскому курсу слитка (250);
 * - отсутствующие цены обозначаются `null`, а не `undefined`: выгрузка
 *   сериализуется в JSON, а JSON не умеет `undefined`;
 * - уровень пирамиды — число 1-7 либо строка «особое» для Академии огня.
 *
 * @module api-types
 * @version 0.9.4
 * @example
 * // Импорт в клиенте стенда:
 * import type { Creature, Army, BattleResult, CreatureId } from './api-types';
 */

