/** Первичные характеристики героя на первом уровне, без артефактов. */
export interface PrimaryStats {
  /** Атака; у Исольды — 0: ни одного наступательного похода за век. */
  attack: number;
  /** Защита; оборонительное мышление города. */
  defense: number;
  /** Сила магии; главный инструмент Владычицы Пепла. */
  spell_power: number;
  /** Знания; гильдейская выучка счёта и архивов. */
  knowledge: number;
}

/** Портрет героя для стенда; полный канон — lore/heroes.md. */
export interface Hero {
  /** Латинский идентификатор героя. */
  id: string;
  /** Полное имя с титулом («Исольда, Владычица Пепла»). */
  name: string;
  /** Класс героя из перечисления {@link HeroClass}. */
  hero_class: HeroClass;
  /** Должность к 910 году («Начальница службы гряды»). */
  position: string;
  /** Специализация словами («ремонт големов дешевле на 20%»). */
  specialization: string;
  /** Характеристики первого уровня; согласованы с data/heroes.json. */
  base_stats: PrimaryStats;
  /** Участвует ли герой в кампании «Огонь и Прах» как действующее лицо. */
  campaign_character: boolean;
  /** Цитаты героя с указанием источника и года. */
  quotes: Array<{
    /** Текст цитаты. */
    text: string;
    /** Источник: архив, школа, устная традиция. */
    source: string;
    /** Год первой фиксации по эрафийскому календарю. */
    year: number;
  }>;
}

