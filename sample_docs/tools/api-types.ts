/** Вид эффекта артефакта: числовой, процентный или особый (призыв, иммунитет). */
export type ArtifactEffectKind = 'flat' | 'percent' | 'special';

/** Один эффект артефакта; у предмета может быть несколько эффектов. */
export interface ArtifactEffect {
  /** Вид эффекта. */
  kind: ArtifactEffectKind;
  /** Цель эффекта словами («сила магии», «все отряды»). */
  target: string;
  /** Числовое значение: +1, +300 золота в день; отсутствует у «особых». */
  value?: number;
  /** Текстовое описание особого эффекта (призыв роя из 7 Искровиков). */
  description?: string;
}

/** Артефакт дополнения; полный список и обоснования — balance/artifacts.md. */
export interface Artifact {
  /** Латинский идентификатор. */
  id: string;
  /** Русское имя («Сердце Кальдеры»). */
  name: string;
  /** Тир предмета. */
  tier: ArtifactTier;
  /** Слот снаряжения. */
  slot: ArtifactSlot;
  /** Эффекты предмета; числовые складываются, процентные берутся наибольшим. */
  effects: ArtifactEffect[];
  /** Цена на рынке приключений; реликвии и набор не продаются — `null`. */
  price_gold: number | null;
  /** Где найти в кампании (может содержать метку [СПОЙЛЕР]). */
  campaign_source: string;
  /** Где найти на карте приключений; подсказка картоделам. */
  map_source: string;
  /** Принадлежность к набору «Регалии Пепла», если предмет — часть набора. */
  set_member?: 'regalii_pepla';
}

/* ==========================================================================
 * Армии и бой
 * ========================================================================== */

/** Отряд армии: существо и численность. */
export interface ArmyStack {
  /** Идентификатор существа из объединения {@link CreatureId}. */
  creature_id: CreatureId;
  /** Численность отряда; целое положительное число. */
  count: number;
}

/**
 * Армия героя или гарнизона.
 *
 * Боевой строй — до семи отрядов; тестовый стенд не пропускает восьмой
 * слот даже ради Лавового Дракона, ибо восемь слотов — это уже не армия,
 * а очередь в Големную печь.
 */
export interface Army {
  /** Герой, ведущий армию; у гарнизона без героя — `undefined`. */
  hero?: Hero;
  /** Отряды армии; от одного до семи. */
  stacks: ArmyStack[];
}

/** Потери стороны боя: идентификатор существа и число погибших голов. */
export type CasualtiesRecord = Partial<Record<CreatureId, number>>;

/** Одна строка журнала боя. */
export interface BattleLogEntry {
  /** Номер раунда, начиная с единицы. */
  round: number;
  /** Сторона, совершившая действие. */
  side: BattleSide;
  /** Человекочитаемое описание действия на русском. */
  message: string;
  /** Нанесённый урон, если строка — про удар. */
  damage?: number;
}

/**
 * Результат боя — контракт `POST /api/v1/battles/simulate`.
 *
 * Стенд воспроизводит упрощённую модель: средний урон, множитель по разнице
 * атаки и защиты, уклонение гарпий 25% при фиксированном зерне. Отчёт
 * отвечает на вопрос «кто остаётся стоять», а не «как это выглядело».
 */
export interface BattleResult {
  /** Идентификатор боя; генерируется стендом. */
  battle_id: string;
  /** Зерно генератора случайных чисел; фиксировано для воспроизводимости. */
  seed: number;
  /** Армия атакующих как она была на начало боя. */
  attacker: Army;
  /** Армия защищающихся. */
  defender: Army;
  /** Итог боя. */
  outcome: BattleOutcome;
  /** Число сыгранных раундов; потолок — 100. */
  rounds: number;
  /** Потери атакующих по существам. */
  attacker_casualties: CasualtiesRecord;
  /** Потери защищающихся. */
  defender_casualties: CasualtiesRecord;
  /** Полный журнал боя; порядок строк воспроизводим при том же зерне. */
  log: BattleLogEntry[];
  /** Метка времени боя в ISO 8601. */
  fought_at: string;
}

/* ==========================================================================
 * Утилитарные типы стенда
 * ========================================================================== */

/** Обнуляемый тип: `Nullable<number>` — число или `null` (для цен из JSON). */
export type Nullable<T> = T | null;

/** Опциональный тип: `Maybe<number>` — число или `undefined` (для полей API). */
export type Maybe<T> = T | undefined;

/** Глубокая readonly-копия типа: ни одно поле не меняется после получения. */
export type DeepReadonly<T> = T extends (infer R)[]
  ? readonly DeepReadonly<R>[]
  : T extends Function
    ? T
    : T extends object
      ? { readonly [K in keyof T]: DeepReadonly<T[K]> }
      : T;

/** JSON-значение: то, что переживает сериализацию без потерь. */
export type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

/** Запись «ключ → существо» для справочников стенда. */
export type CreatureRecord = Record<CreatureId, Creature>;

/** Фильтр по уровню: конкретный уровень или «все». */
export type TierFilter = CreatureTier | 'все';

/** Ответ API с полезной нагрузкой; используется всеми GET-эндпоинтами. */
export interface ApiResponse<T> {
  /** `true` при успехе; при `false` читайте `error`. */
  ok: boolean;
  /** Полезная нагрузка; присутствует только при успехе. */
  data?: T;
  /** Ошибка; присутствует только при неудаче. */
  error?: ApiError;
}

/** Ошибка API с машинным кодом и человекочитаемым сообщением. */
export interface ApiError {
  /** Стабильный машинный код из {@link ApiErrorCode}. */
  code: ApiErrorCode;
  /** Сообщение на русском; для плейтестеров, не для парсеров. */
  message: string;
  /** Дополнительные поля ошибки; зависят от кода. */
  details?: Json;
}

/** Страница списка: существа, герои, артефакты, бои. */
export interface Paginated<T> {
  /** Элементы текущей страницы. */
  items: T[];
  /** Номер страницы, начиная с единицы. */
  page: number;
  /** Размер страницы. */
  page_size: number;
  /** Всего элементов на всех страницах. */
  total: number;
}

/** Смета стоимости армии: золото, слитки и эффективное золото. */
export interface CostBreakdown {
  /** Сумма цен найма в золоте. */
  gold: number;
  /** Сумма цен найма в слитках; ноль, если драконов в армии нет. */
  ingots: number;
  /** Эффективное золото: `gold + ingots × 250` по городскому курсу. */
  effective_gold: number;
}

/** Сводные показатели армии, посчитанные калькулятором tools/army_calculator.py. */
export interface ArmySummary {
  /** Общее число голов. */
  heads: number;
  /** Суммарное здоровье армии. */
  total_health: number;
  /** Минимальный урон за раунд с учётом множителя. */
  min_damage: number;
  /** Максимальный урон за раунд с учётом множителя. */
  max_damage: number;
  /** Ожидаемый (средний) урон за раунд. */
  avg_damage: number;
  /** Армейская мощь: сумма оценок ИИ по всем головам. */
  power: number;
  /** Скорость самого быстрого отряда армии. */
  best_speed: number;
  /** Число отрядов в армии. */
  stacks: number;
  /** Смета найма армии. */
  cost: CostBreakdown;
}
